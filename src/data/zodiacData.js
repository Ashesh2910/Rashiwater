/**
 * Returns the daily horoscope for a sign based on the current date.
 * Rotates through the 7-message pool using day-of-year.
 */
export function getDailyHoroscope(signName) {
  const sign = zodiacData.find((s) => s.name === signName);
  if (!sign) return '';
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now - start;
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  // Add a per-sign offset so each sign gets a different message on the same day
  const signIndex = zodiacData.indexOf(sign);
  const idx = (dayOfYear + signIndex * 3) % sign.horoscopes.length;
  return sign.horoscopes[idx];
}

/**
 * Returns the zodiac data object for a given sign name.
 */
export function getZodiacByName(name) {
  return zodiacData.find((s) => s.name === name) || null;
}

